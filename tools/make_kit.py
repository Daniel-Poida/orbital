def artist_readme(d, hints, kit_dir):
    bpm = d['bpm']
    lines = [f"# {d['name']}: что прислать", '',
             f"Пример планеты, которая сейчас на сайте. Звуки в нём синтетические, их нужно заменить настоящими из трека. Общие требования — в [README](../README.md).",
             '', f"**Темп:** {bpm} BPM. Луп на 4 такта = {sec(4 * 240 / bpm)} с.", '',
             '## Звуки ударки', '', '| Файл | Что записать |', '|---|---|']
    for i, s in enumerate(d['samples']):
        fn = f"{i + 1:02d} {safe(s['name'])}.wav"
        lines.append(f"| `drums/{fn}` | {hints.get(s['name'], 'короткий звук из трека')} |")
    lines += ['', '## Лупы (кольца)', '', '| Файл | Длина | Что записать |', '|---|---|---|']
    for i, r in enumerate(d['rings']):
        b = r.get('bars', 4)
        fn = f"{i + 1:02d} {safe(r['name'])} ({b} {bar_word(b)}).wav"
        lines.append(f"| `loops/{fn}` | {sec(b * 240 / bpm)} с | {hints.get(r['name'], 'партия из трека')} |")
    lines += ['', '## Картинки', '',
              '- `textures/planet.png` — поверхность планеты. В примере 512×512, для настоящей лучше 2048×1024.',
              '- `textures/background.png` — фон экрана. В примере PNG 512×512, для настоящего нужен вертикальный JPG 1080×1920.',
              '', 'Слоты и подписи можно менять: переименуйте файл, уберите лишний или добавьте свой с новым номером.', '']
    return '\n'.join(lines)


def main():
    if os.path.isdir(KIT):
        shutil.rmtree(KIT)
    os.makedirs(KIT)
    write(os.path.join(KIT, 'README.md'), main_readme())

    tpl = os.path.join(KIT, '_шаблон')
    write(os.path.join(tpl, 'анкета.txt'), ANKETA.format(name='', track='', bpm='', url='', accent='', orbit='', ray='', text='', comment=''))
    for sub, note in (('textures', 'Сюда: planet.png (2048×1024) и background.jpg (1080×1920).'),
                      ('drums', 'Сюда: 6–12 коротких звуков. Имя: «01 Бочка.wav».'),
                      ('loops', 'Сюда: 3–8 лупов ровно в тактах. Имя: «01 Пад (4 такта).wav».')):
        write(os.path.join(tpl, sub, 'ЧТО СЮДА.txt'), note + '\n')

    index = json.load(open(os.path.join(PLANETS, 'index.json'), encoding='utf-8'))
    for entry in index['planets']:
        pid = entry['id']
        src = os.path.join(PLANETS, pid)
        d = json.load(open(os.path.join(src, 'planet.json'), encoding='utf-8'))
        dst = os.path.join(KIT, safe(d['name']))
        c = d.get('colors', {})
        write(os.path.join(dst, 'анкета.txt'), ANKETA.format(
            name=d['name'], track=d.get('track', ''), bpm=d['bpm'], url=d.get('trackUrl', ''),
            accent=c.get('accent', ''), orbit=c.get('orbit', ''), ray=c.get('ray', ''), text=c.get('text', ''), comment=''))
        os.makedirs(os.path.join(dst, 'textures'), exist_ok=True)
        if d.get('texture'):
            shutil.copy(os.path.join(src, d['texture']), os.path.join(dst, 'textures', 'planet' + os.path.splitext(d['texture'])[1]))
        if d.get('background'):
            shutil.copy(os.path.join(src, d['background']), os.path.join(dst, 'textures', 'background' + os.path.splitext(d['background'])[1]))
        os.makedirs(os.path.join(dst, 'drums'), exist_ok=True)
        for i, s in enumerate(d['samples']):
            ext = os.path.splitext(s['file'])[1]
            shutil.copy(os.path.join(src, s['file']), os.path.join(dst, 'drums', f"{i + 1:02d} {safe(s['name'])}{ext}"))
        os.makedirs(os.path.join(dst, 'loops'), exist_ok=True)
        for i, r in enumerate(d['rings']):
            ext = os.path.splitext(r['file'])[1]
            b = r.get('bars', 4)
            shutil.copy(os.path.join(src, r['file']), os.path.join(dst, 'loops', f"{i + 1:02d} {safe(r['name'])} ({b} {bar_word(b)}){ext}"))
        write(os.path.join(dst, 'README.md'), artist_readme(d, HINTS.get(pid, {}), dst))
        print('kit', d['name'])
    print('done')


if __name__ == '__main__':
    main()
